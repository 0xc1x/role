function replaceFills(inner, color) {
	return inner
		.replace(/\bfill="[^"]+"/gi, `fill="${color}"`)
		.replace(/\bfill\s*:\s*[^;\"]+/gi, `fill:${color}`);
}

/** White wordmark variant for dark surfaces (boot splash, app splashes). */
function whiteInner(inner, paper) {
	return replaceFills(inner, paper);
}

/** Monochrome wordmark variant: every fill becomes currentColor so each app
 *  tints it with a text color class (e.g. admin sidebar foreground). */
function monoInner(inner) {
	return replaceFills(inner, "currentColor");
}

/**
 * The new wordmark's artwork reaches the edge of its design viewBox. The old
 * wordmark carried optical breathing room in the artwork itself, so rendering
 * both at the same CSS height made the new one look oversized everywhere.
 * Keep the canonical SVG untouched and add the shared presentation treatment
 * to every runtime consumer instead.
 */
const WORDMARK_OPTICAL_SCALE = 0.8;

function layoutInner(inner, viewBox) {
	const [, , width, height] = viewBox.split(" ").map(Number);
	const cx = width / 2;
	const cy = height / 2;
	const transform = `translate(${cx} ${cy}) scale(${WORDMARK_OPTICAL_SCALE}) translate(${-cx} ${-cy})`;
	return `<g transform="${transform}">${inner}</g>`;
}

/**
 * The canonical icon is authored full-bleed: its dark tile touches every edge
 * of the viewBox, so a face-value rasterization has no breathing room and the
 * R reads oversized inside the launcher frame. As with the wordmark, the fix
 * is a shared presentation treatment applied at raster time — the canonical
 * SVG stays untouched, and every ICON surface (launcher, adaptive foreground,
 * PWA manifest sizes, maskable, apple-touch, monochrome glyph) renders the
 * same letterbox. Favicons are a different surface class (they compete for
 * pixels at 16-48px) and keep the full-bleed render.
 */
const ICON_OPTICAL_SCALE = 0.8;

/** Letterbox the icon artwork about the center of its own viewBox. */
function padIconInner(inner, viewBox, scale = ICON_OPTICAL_SCALE) {
	const [, , width, height] = viewBox.split(" ").map(Number);
	const cx = width / 2;
	const cy = height / 2;
	const transform = `translate(${cx} ${cy}) scale(${scale}) translate(${-cx} ${-cy})`;
	return `<g transform="${transform}">${inner}</g>`;
}

/** Same letterbox wrapped in a standalone SVG for the raster pipelines. */
function padIconAsset(asset, scale = ICON_OPTICAL_SCALE) {
	return (
		`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${asset.viewBox}">\n` +
		`${padIconInner(asset.inner, asset.viewBox, scale)}</svg>\n`
	);
}

