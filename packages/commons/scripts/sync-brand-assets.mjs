/**
 * brand:sync — regenerate every brand artifact from the single source of truth.
 *
 * Sources (edit these, nothing else):
 *   packages/commons/src/brand/assets/icon.svg      (canonical logo/icon)
 *   packages/commons/src/brand/assets/wordmark.svg  (canonical wordmark)
 *   packages/commons/src/brand/tokens.ts            (palette + BRAND_ASSET_VERSION)
 *
 * Generated (do not hand-edit — `brand:check` enforces it in CI):
 *   packages/commons/src/brand/icon.ts + wordmark.ts (VIEWBOX/INNER/SVG strings
 *     imported by admin, landing and mobile — UI updates on rebuild).
 *     `icon.ts` carries the TRANSPARENT treatment (background rect removed
 *     when the canonical still has one; already-transparent canonicals pass
 *     through). Surfaces requiring opacity (apple-touch) flatten on cream
 *     at PNG time.
 *   packages/commons/src/brand/mark.ts (MARK_R_* lone glyph + MARK_FULL_*
 *     transparent logo mark: sparkles + R, tile removed, R on currentColor).
 *   apps/admin/public/{icon,wordmark}.svg (icon = transparent treatment)
 *   apps/landing/public/{icon,wordmark}.svg (icon = transparent treatment)
 *   apps/mobile/assets/svgs/role_wordmark.svg
 *
 * Usage:
 *   bun run brand:sync            # codegen + SVG copies + ?v= cache-bust
 *   bun run brand:sync -- --png   # also regenerate PNGs (needs `sharp`)
 *   bun run brand:check           # verify every generated file matches (CI)
 *
 * After sync: rebuild commons + apps. Mobile launcher icons need an EAS
 * rebuild. Legacy `favicon.ico` files and `og.png` cards are NOT regenerated
 * (one-time external tools); modern browsers already use `icon.svg`.
 */
